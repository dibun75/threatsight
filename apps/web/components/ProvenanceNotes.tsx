type Provenance = {
  data_origin?: string | null;
  evidence_source?: string | null;
  generated_by?: string | null;
  last_updated?: string | null;
  validation?: string | null;
  extraction_method?: string | null;
  human_review?: string | null;
};

function formatStamp(value: string): string {
  const parsed = new Date(value);
  if (Number.isNaN(parsed.getTime())) {
    return value;
  }
  return `${parsed.toISOString().slice(0, 19).replace("T", " ")} UTC`;
}

export function ProvenanceNotes({ value }: { value?: Provenance | null }) {
  if (!value) {
    return null;
  }
  const rows: Array<[string, string]> = [];
  if (value.data_origin) {
    rows.push(["Data origin", value.data_origin]);
  }
  if (value.evidence_source) {
    rows.push(["Evidence source", value.evidence_source]);
  }
  if (value.generated_by) {
    rows.push(["Generated by", value.generated_by]);
  }
  if (value.validation) {
    rows.push(["Validation", value.validation]);
  }
  if (value.extraction_method) {
    rows.push(["Extraction method", value.extraction_method]);
  }
  if (value.human_review) {
    rows.push(["Human review", value.human_review]);
  }
  if (value.last_updated) {
    rows.push(["Last updated", formatStamp(value.last_updated)]);
  }
  if (rows.length === 0) {
    return null;
  }
  return (
    <dl className="provenance">
      {rows.map(([label, text]) => (
        <div key={label}>
          <dt>{label}</dt>
          <dd>{text}</dd>
        </div>
      ))}
    </dl>
  );
}
